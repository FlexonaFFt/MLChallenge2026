# Few-shot примеры в формате эталонов (показ формата сильнее инструкций).
# Общий префикс кэшируется (prefix caching), поэтому почти бесплатно по времени.
FEW_SHOT: list[tuple[str, str]] = [
    (
        "Вычислите значение выражения 6032 − 6012.",
        "Вычислим значение выражения $6032 - 6012$:\n\n"
        "$$\n6032 - 6012 = 20\n$$\n\n**Ответ:** $20$",
    ),
    (
        "в слове «медовый» где корень, суффикс, окончание?",
        "Разберём слово **«медовый»** по составу:\n\n"
        "- **корень**: *мед-* (от слова «мёд»);\n"
        "- **суффикс**: *-ов-* (образует прилагательное от существительного);\n"
        "- **окончание**: *-ый* (мужской род, единственное число, именительный падеж).\n\n"
        "Схема: **мед‑ов‑ый** (корень — суффикс — окончание).",
    ),
]


@dataclass
class InferenceConfig:
    model_dir: str = "./weights"
    max_new_tokens: int = 768
    max_model_len: int = 4096
    gpu_memory_utilization: float = 0.9
    temperature: float = 0.0
    system_prompt: str = field(default=SYSTEM_PROMPT)
    few_shot: list[tuple[str, str]] = field(default_factory=lambda: FEW_SHOT)
    enable_prefix_caching: bool = True
    max_num_seqs: int = 256
